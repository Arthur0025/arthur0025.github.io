          <p>这种分解之所以强大，是因为每个傅里叶系数精确地告诉我们原始信号中频率 <em>n</em> 的含量。例如，方波只包含奇次谐波，且振幅以 1/<em>n</em> 的速度衰减——这一事实解释了在尖锐边缘处出现的"振铃"现象（吉布斯现象）。理解这种分解是理解傅里叶方法为何在 PDE 求解中如此有效的第一步：在频率域中，许多微分算子变成了简单的代数乘法。</p>

